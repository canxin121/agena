#!/usr/bin/env python3
"""Verify real Vue controls in an isolated browser without server mutations.

Start Vite, then run:
uv run --with playwright python scripts/verify-keyboard-navigation.py --base http://127.0.0.1:5175
"""
import argparse
import json
from pathlib import Path

from playwright.sync_api import expect, sync_playwright


def verify(browser, base, output):
    checks = []

    def check(name, condition):
        assert condition, name
        checks.append(name)

    page = browser.new_page(viewport={"width": 1280, "height": 850})
    page.set_default_timeout(5000)
    page.set_default_navigation_timeout(30000)
    errors = []
    page.on("pageerror", lambda error: errors.append(str(error)))
    fixture = base.rstrip("/") + "/tests/fixtures/keyboard-navigation.html"

    def reset():
        page.goto(fixture)
        expect(page.locator("#help-trigger")).to_be_visible()

    reset()
    page.locator("#help-trigger").focus()
    page.keyboard.press("Enter")
    dialog = page.get_by_role("dialog")
    body = dialog.locator("[data-dialog-body]")
    expect(body).to_have_attribute("tabindex", "0")
    check("dialog body defaults to native scrolling", body.evaluate("e => getComputedStyle(e).overflowY === 'auto'"))
    page.keyboard.press("Tab")
    expect(body).to_be_focused()
    page.keyboard.press("End")
    page.wait_for_function("(() => {const e = document.querySelector('[data-dialog-body]'); return Math.abs(e.scrollHeight - e.clientHeight - e.scrollTop) < 2})()")
    check("help End reaches the last shortcuts", body.evaluate("e => Math.abs(e.scrollHeight - e.clientHeight - e.scrollTop) < 2"))
    page.screenshot(path=str(output / "help-desktop-bottom.png"))
    page.keyboard.press("Home")
    page.wait_for_function("document.querySelector('[data-dialog-body]').scrollTop === 0")
    body.hover()
    page.mouse.wheel(0, 600)
    page.wait_for_function("document.querySelector('[data-dialog-body]').scrollTop > 100")
    check("help responds to wheel scrolling", True)
    before = page.evaluate("window.keyboardFixture.ui.activeMainTab")
    page.keyboard.press("Control+2")
    page.keyboard.press("Control+n")
    check("modal blocks background navigation and session creation", page.evaluate("window.keyboardFixture.state.created === 0") and page.evaluate("window.keyboardFixture.ui.activeMainTab") == before)
    for index in range(9):
        page.keyboard.press("Tab")
        check(f"help focus remains in dialog after Tab {index + 1}", dialog.evaluate("e => e.contains(document.activeElement)"))
    page.keyboard.press("Escape")
    expect(page.locator("#help-trigger")).to_be_focused()
    expect(dialog).to_have_count(0)
    check("help Escape restores its trigger", True)

    page.evaluate("async () => { await window.keyboardFixture.router.push('/settings/interface') }")
    page.get_by_role("button", name="Open form", exact=True).focus()
    page.keyboard.press("Enter")
    form = page.get_by_role("dialog", name="Fixture form", exact=True)
    expect(form.get_by_role("button", name="关闭", exact=True)).to_be_focused()
    page.keyboard.press("Tab")
    expect(form.get_by_role("textbox", name="Form input", exact=True)).to_be_focused()
    page.keyboard.press("Escape")
    expect(form).to_have_count(0)
    expect(page.get_by_role("button", name="Open form", exact=True)).to_be_focused()
    check("closing a settings dialog does not also exit settings", page.evaluate("window.keyboardFixture.router.currentRoute.value.path === '/settings/interface'"))

    page.locator("#menu-trigger").focus()
    page.keyboard.press("Enter")
    menu = page.get_by_role("dialog")
    expect(menu.locator("input")).to_be_focused()
    page.keyboard.press("ArrowDown")
    expect(menu.get_by_role("button", name="Option 0", exact=True)).to_be_focused()
    page.keyboard.press("ArrowUp")
    expect(menu.get_by_role("button", name="Option 29", exact=True)).to_be_focused()
    check("option arrows skip disabled items and wrap", True)
    page.keyboard.press("Home")
    expect(menu.get_by_role("button", name="Option 0", exact=True)).to_be_focused()
    page.keyboard.press("End")
    expect(menu.get_by_role("button", name="Option 29", exact=True)).to_be_focused()
    check("last menu option is scrolled into view", menu.get_by_role("button", name="Option 29", exact=True).evaluate("e => {const r=e.getBoundingClientRect(), p=e.parentElement.parentElement.getBoundingClientRect(); return r.bottom <= p.bottom+2}"))
    page.keyboard.press("Enter")
    expect(menu).to_have_count(0)
    expect(page.locator("#menu-trigger")).to_be_focused()
    check("option Enter selects and restores focus", page.evaluate("window.keyboardFixture.state.selected === 'option-29'"))
    page.keyboard.press("Enter")
    page.keyboard.press("Escape")
    expect(page.locator("#menu-trigger")).to_be_focused()
    check("option Escape restores focus", True)

    page.evaluate("window.keyboardFixture.ui.setIsCompactTouch(true)")
    page.locator("#menu-trigger").focus()
    page.keyboard.press("Enter")
    expect(page.get_by_role("dialog")).to_be_visible()
    page.keyboard.press("ArrowDown")
    expect(page.get_by_role("dialog").get_by_role("button", name="Option 0", exact=True)).to_be_focused()
    page.keyboard.press("Enter")
    expect(page.locator("#menu-trigger")).to_be_focused()
    check("touch sheet supports keyboard selection and focus restoration", page.evaluate("window.keyboardFixture.state.selected === 'option-0'"))
    page.evaluate("window.keyboardFixture.ui.setIsCompactTouch(false)")

    picker = page.get_by_role("button", name="Fixture picker:")
    picker.focus()
    page.keyboard.press("ArrowDown")
    menu = page.get_by_role("dialog")
    expect(menu.locator("input")).to_be_focused()
    menu.locator("input").fill("Option 12")
    page.keyboard.press("Enter")
    expect(picker).to_be_focused()
    check("picker keyboard search selects a filtered item", page.evaluate("window.keyboardFixture.state.choice === 'option-12'"))

    inline = page.locator('input[aria-haspopup="dialog"]')
    inline.focus()
    page.keyboard.press("ArrowDown")
    expect(page.get_by_role("dialog").get_by_role("button", name="Option 0", exact=True)).to_be_focused()
    page.keyboard.press("ArrowDown")
    page.keyboard.press("Enter")
    expect(inline).to_be_focused()
    check("inline picker can select a non-first option", page.evaluate("window.keyboardFixture.state.adds[0] === 'option-1'"))
    page.keyboard.press("Escape")
    expect(page.get_by_role("dialog")).to_have_count(0)
    check("inline Escape dismisses only its own suggestions", True)
    page.keyboard.press("Tab")
    expect(page.get_by_role("dialog")).to_have_count(0)
    check("inline suggestions close when focus leaves", True)

    reset()
    page.locator("#help-trigger").focus()
    page.keyboard.press("F6")
    expect(page.locator("#sidebar-control")).to_be_focused()
    page.keyboard.press("F6")
    expect(page.locator("#terminal-input")).to_be_focused()
    page.keyboard.press("Shift+F6")
    expect(page.locator("#sidebar-control")).to_be_focused()
    check("F6 and Shift F6 cycle regions", True)
    page.locator("#terminal-input").focus()
    page.keyboard.press("Control+h")
    page.keyboard.press("Control+l")
    check("terminal Ctrl H and Ctrl L retain shell ownership", page.get_by_role("dialog").count() == 0)
    page.keyboard.press("Alt+Shift+i")
    expect(page.locator("#composer-first")).to_be_focused()
    page.evaluate("window.keyboardFixture.ui.selectWorkspaceWindow(window.keyboardFixture.second)")
    page.keyboard.press("Alt+Shift+i")
    expect(page.locator("#composer-second")).to_be_focused()
    check("input shortcut chooses the focused pane composer", True)
    page.keyboard.press("Alt+Shift+5")
    page.wait_for_function("window.keyboardFixture.ui.activeMainTab === 'git'")
    check("alternative page shortcut navigates", True)
    page.keyboard.press("Control+6")
    check("unmapped number leaves page unchanged", page.evaluate("window.keyboardFixture.ui.activeMainTab === 'git'"))

    reset()
    first_tab = page.locator("[data-workspace-tab-primary]").first
    first_tab.focus()
    page.keyboard.press("ArrowRight")
    expect(page.locator("[data-workspace-tab-primary]").nth(1)).to_be_focused()
    check("workspace arrow changes tab and focus together", page.evaluate("window.keyboardFixture.ui.activeWorkspaceWindowId === window.keyboardFixture.second"))
    page.keyboard.press("Shift+F10")
    expect(page.get_by_role("dialog")).to_be_visible()
    page.keyboard.press("Escape")
    expect(page.locator("[data-workspace-tab-primary]").nth(1)).to_be_focused()
    page.keyboard.press("Delete")
    expect(page.locator("[data-workspace-tab-primary]")).to_have_count(1)
    expect(page.locator("[data-workspace-tab-primary]")).to_be_focused()
    check("tab context menu and Delete retain usable focus", True)

    page.keyboard.press("Shift+F10")
    menu = page.get_by_role("dialog")
    menu.get_by_role("button", name="关闭所有窗口", exact=True).focus()
    page.keyboard.press("Enter")
    expect(page.locator("[data-workspace-tab-primary]")).to_have_count(0)
    expect(page.locator("#help-trigger")).to_be_focused()
    check("closing all tabs returns focus to a surviving region", page.evaluate("window.keyboardFixture.router.currentRoute.value.path === '/'"))

    reset()
    sep = page.get_by_role("separator")
    sep.focus()
    page.keyboard.press("ArrowLeft")
    check("horizontal splitter supports arrows", page.evaluate("window.keyboardFixture.state.rightWidth === 236"))
    page.keyboard.press("End")
    check("horizontal splitter clamps to its maximum", page.evaluate("window.keyboardFixture.state.rightWidth === 400"))
    page.evaluate("window.keyboardFixture.state.showRight = false")
    expect(page.locator("#hidden-pane-control").locator("..")).to_have_attribute("inert", "")
    check("collapsed pane is removed from keyboard focus", True)
    expect(page.get_by_role("button", name="Named icon", exact=True)).to_be_visible()
    expect(page.get_by_role("button", name="Named sidebar icon", exact=True)).to_be_visible()
    check("icon-only controls have accessible names", True)

    for width, height in [(390, 640), (844, 390)]:
        page.set_viewport_size({"width": width, "height": height})
        reset()
        page.locator("#help-trigger").focus()
        page.keyboard.press("Enter")
        body = page.get_by_role("dialog").locator("[data-dialog-body]")
        body.focus()
        page.keyboard.press("End")
        page.wait_for_function("(() => {const e = document.querySelector('[data-dialog-body]'); return Math.abs(e.scrollHeight - e.clientHeight - e.scrollTop) < 2})()")
        check(f"help fits and scrolls at {width} by {height}", page.get_by_role("dialog").evaluate("e => {const r=e.getBoundingClientRect();return r.top>=0 && r.bottom<=innerHeight && r.left>=0 && r.right<=innerWidth}"))
        page.screenshot(path=str(output / f"help-{width}-{height}.png"))
        page.keyboard.press("Escape")
    check("browser has no uncaught component errors", not errors)
    page.close()
    return {"passed": len(checks), "checks": checks, "errors": errors}


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--base", default="http://127.0.0.1:5175")
    parser.add_argument("--output", default="../../.tmp-artifacts/keyboard-navigation")
    args = parser.parse_args()
    output = Path(args.output).resolve()
    output.mkdir(parents=True, exist_ok=True)
    with sync_playwright() as playwright:
        browser = playwright.chromium.launch(channel="chrome", headless=True)
        try:
            result = verify(browser, args.base, output)
            (output / "verification.json").write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n")
            print(json.dumps(result, ensure_ascii=False, indent=2))
        finally:
            browser.close()
