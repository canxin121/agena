export type TelegramCopyKey = keyof typeof messages
export function useTelegramCopy() {
  const { locale } = useI18n()
  const tx = (key: TelegramCopyKey) => messages[key][String(locale.value).startsWith('zh') ? 0 : 1]
  const kindLabel = (kind: string) =>
    ['direct', 'group', 'broadcast'].includes(kind) ? tx(kind as TelegramCopyKey) : tx('unknown')
  const stateLabel = (state: string) => (state in messages ? tx(state as TelegramCopyKey) : state)
  const date = (ms?: number | null) =>
    ms && Number.isFinite(ms) ? new Date(ms).toLocaleString(String(locale.value)) : tx('never')
  return { tx, kindLabel, stateLabel, date, locale }
}
